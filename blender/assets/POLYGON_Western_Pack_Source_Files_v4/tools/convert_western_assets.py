"""POLYGON Western -> granular Blender Asset Browser library (Blender 5.2.x)."""
import json
import os
import re
import traceback
import uuid
from datetime import datetime, timezone
from pathlib import Path

import bpy

PACK = Path(r"D:\Godot\xybotsResearch\blender\assets\POLYGON_Western_Pack_Source_Files_v4")
SOURCE = PACK / "SourceFiles"
LIBRARY = PACK / "BlenderAssets"
LOGS = PACK / "conversion_logs"
MANIFEST = SOURCE / "MaterialList_PolygonWestern.txt"
CATALOG_FILE = LIBRARY / "blender_assets.cats.txt"
NAMESPACE = uuid.UUID("4fbf08d7-4b45-5d5e-90d1-1ab3a89b3d42")


def _catalog_id(path):
    return str(uuid.uuid5(NAMESPACE, path))


def _clean_name(name):
    return re.sub(r"\s+", " ", re.sub(r"[_-]+", " ", name)).strip()


def _load_manifest():
    """Return {FBX base name: (catalog, {material: texture file})} from vendor data."""
    result, category, asset, slots = {}, None, None, {}
    if not MANIFEST.exists():
        return result
    def finish():
        if asset:
            result[asset] = (category or "Uncategorized", dict(slots))
    for line in MANIFEST.read_text(encoding="utf-8", errors="replace").splitlines():
        match = re.match(r"Folder Name:\s*(.+)", line)
        if match:
            finish(); category = match.group(1).strip(); asset = None; slots = {}; continue
        match = re.match(r"Prefab Name:\s*(.+)", line)
        if match:
            finish(); asset = match.group(1).strip(); slots = {}; continue
        match = re.match(r"\s*Slot:\s*(.+?)\s*\((.+?)\)\s*$", line)
        if match and asset:
            slots[match.group(1).strip()] = match.group(2).strip()
    finish()
    return result


def _catalog_for(name, manifest):
    if name in manifest:
        return manifest[name][0]
    if name.startswith("SK_Character") or "Character" in name:
        return "Characters"
    if name.startswith("SM_Bld"):
        return "Buildings"
    if name.startswith("SM_Env") or name == "SkyDome":
        return "Environments"
    if name.startswith("SM_Veh"):
        return "Vehicles"
    if name.startswith("SM_Wep"):
        return "Weapons"
    if name.startswith("SM_Particle"):
        return "FX"
    return "Props"


def _ensure_catalogs(categories):
    LIBRARY.mkdir(parents=True, exist_ok=True)
    lines = ["VERSION 1", "# Generated by POLYGON Western Blender 5.2 asset conversion."]
    for category in sorted(categories):
        path = "POLYGON Western/" + category
        lines.append(f"{_catalog_id(path)}:{path}:{category}")
    CATALOG_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")


def discover():
    """Only canonical FBX exports become assets; alternate Unreal exports remain source."""
    files = []
    fbx = SOURCE / "FBX"
    for path in sorted(fbx.glob("*.fbx")):
        if path.stem in {"Characters", "POLYGON_Western_Demo_Scene"}:
            continue
        files.append(path)
    for path in sorted((SOURCE / "Characters").glob("*.fbx")):
        files.append(path)
    return files


def _import_fbx(path):
    before = set(bpy.data.objects)
    if hasattr(bpy.ops.import_scene, "fbx"):
        bpy.ops.import_scene.fbx(filepath=str(path), use_image_search=False)
    elif hasattr(bpy.ops.wm, "fbx_import"):
        bpy.ops.wm.fbx_import(filepath=str(path))
    else:
        raise RuntimeError("No FBX importer is available in this Blender installation.")
    return list(set(bpy.data.objects) - before)


def _texture_path(texture_name):
    if not texture_name:
        return None
    candidate = SOURCE / "Textures" / (texture_name if Path(texture_name).suffix else texture_name + ".png")
    return candidate if candidate.exists() else None


def _material_key(name):
    return re.sub(r"[^a-z0-9]", "", name.lower())


def _reconnect_materials(objects, slots, output_dir):
    """Only attach an exact vendor-manifest diffuse atlas; never guess PBR channels."""
    missing, questionable, resolved = [], [], []
    seen = set()
    for obj in objects:
        if obj.type != "MESH":
            continue
        for mat in obj.data.materials:
            if not mat or mat.name in seen:
                continue
            seen.add(mat.name)
            # The live conversion session may already contain an identically named
            # material, so Blender appends .001 etc.  The vendor manifest names the
            # unsuffixed material name.
            manifest_name = re.sub(r"\.\d{3}$", "", mat.name)
            # Maya/FBX export changes both case and the placement of underscores
            # (POLYGON_Western vs PolygonWestern), so compare normalized names.
            normalized_slots = {_material_key(key): value for key, value in slots.items()}
            texture_name = slots.get(manifest_name) or normalized_slots.get(_material_key(manifest_name))
            # Maya exports many meshes with the generic lambert1 material.  When
            # the vendor manifest declares exactly one atlas for this FBX, that
            # assignment is unambiguous even though the material name is generic.
            unique_textures = sorted(set(slots.values()))
            if not texture_name and len(unique_textures) == 1:
                texture_name = unique_textures[0]
            texture = _texture_path(texture_name)
            if not texture:
                questionable.append(mat.name)
                continue
            try:
                mat.use_nodes = True
                nodes, links = mat.node_tree.nodes, mat.node_tree.links
                principled = next((n for n in nodes if n.type == "BSDF_PRINCIPLED"), None)
                if not principled:
                    questionable.append(mat.name); continue
                # FBX commonly creates an image node pointing to a PSD path that
                # is not distributed in this pack. Reuse it, replacing that stale
                # image with the exact PNG named by the vendor material manifest.
                image_node = next((n for n in nodes if n.type == "TEX_IMAGE"), None)
                if not image_node:
                    image_node = nodes.new("ShaderNodeTexImage")
                image = bpy.data.images.load(str(texture), check_existing=True)
                image.filepath = "//" + os.path.relpath(texture, output_dir).replace("\\", "/")
                image_node.image = image
                if not any(link.to_node == principled and link.to_socket == principled.inputs.get("Base Color") for link in links):
                    links.new(image_node.outputs["Color"], principled.inputs["Base Color"])
                resolved.append(mat.name)
            except Exception:
                missing.append(mat.name)
    return {"resolved": sorted(set(resolved)), "missing": sorted(set(missing)), "questionable": sorted(set(questionable))}


def _hide_helpers(objects):
    helpers = []
    for obj in objects:
        if re.search(r"(^UCX_|^UBX_|COLLIDER|COLLISION|^COL_)", obj.name, re.I):
            obj.hide_viewport = obj.hide_render = True
            helpers.append(obj.name)
    return helpers


def _render_preview(scene, collection):
    """Render a compact 3/4 workbench preview without saving preview-only IDs."""
    from mathutils import Vector
    # Allocate Blender's asset-preview datablock first; the automatic preview
    # itself is intentionally replaced by the deterministic workbench render.
    collection.asset_generate_preview()
    points = []
    for obj in collection.objects:
        if obj.type == "MESH" and not obj.hide_render:
            points.extend(obj.matrix_world @ Vector(corner) for corner in obj.bound_box)
    if not points:
        return False
    low = Vector((min(v[i] for v in points) for i in range(3)))
    high = Vector((max(v[i] for v in points) for i in range(3)))
    center, extent = (low + high) * 0.5, high - low
    scale = max(extent.x, extent.y, extent.z, 0.1)
    camera_data = bpy.data.cameras.new("__asset_preview_camera__")
    camera = bpy.data.objects.new("__asset_preview_camera__", camera_data)
    scene.collection.objects.link(camera)
    camera_data.type = "ORTHO"; camera_data.ortho_scale = scale * 1.55
    camera.location = center + Vector((scale * 1.8, -scale * 1.8, scale * 1.35))
    camera.rotation_euler = (center - camera.location).to_track_quat("-Z", "Y").to_euler()
    scene.camera = camera
    scene.render.engine = "BLENDER_WORKBENCH"
    scene.display.shading.light = "STUDIO"
    scene.display.shading.studiolight_rotate_z = 0.45
    scene.display.shading.background_type = "WORLD"
    scene.display.shading.background_color = (0.055, 0.055, 0.055)
    scene.render.resolution_x = scene.render.resolution_y = 128
    scene.render.resolution_percentage = 100
    LOGS.mkdir(parents=True, exist_ok=True)
    preview_file = LOGS / "__asset_preview_render.png"
    scene.render.image_settings.file_format = "PNG"
    scene.render.filepath = str(preview_file)
    bpy.ops.render.render(write_still=True)
    preview = collection.preview
    preview.image_size = (128, 128)
    rendered = bpy.data.images.load(str(preview_file), check_existing=False)
    pixels = rendered.pixels[:]
    # ImagePreview uses one packed 32-bit RGBA value per pixel, unlike Image.
    preview.image_pixels = [
        int(max(0, min(255, pixels[i] * 255)))
        | (int(max(0, min(255, pixels[i + 1] * 255))) << 8)
        | (int(max(0, min(255, pixels[i + 2] * 255))) << 16)
        | (int(max(0, min(255, pixels[i + 3] * 255))) << 24)
        for i in range(0, len(pixels), 4)
    ]
    bpy.data.images.remove(rendered)
    if preview_file.exists():
        preview_file.unlink()
    bpy.data.objects.remove(camera, do_unlink=True)
    # The object removal can already free its datablock in some 5.2 contexts.
    if camera_data.name in bpy.data.cameras and camera_data.users == 0:
        bpy.data.cameras.remove(camera_data)
    return True


def _write_asset(path, manifest):
    name = path.stem
    category = _catalog_for(name, manifest)
    output = LIBRARY / category / (name + ".blend")
    output.parent.mkdir(parents=True, exist_ok=True)
    original_scene = bpy.context.window.scene
    temporary_scene = bpy.data.scenes.new("__POLYGON_Western_Conversion__")
    asset_collection = None
    imported = []
    try:
        bpy.context.window.scene = temporary_scene
        imported = _import_fbx(path)
        if not imported:
            raise RuntimeError("FBX import created no objects")
        asset_collection = bpy.data.collections.new(_clean_name(name))
        temporary_scene.collection.children.link(asset_collection)
        for obj in imported:
            asset_collection.objects.link(obj)
            for collection in list(obj.users_collection):
                if collection != asset_collection:
                    collection.objects.unlink(obj)
        slots = manifest.get(name, (None, {}))[1]
        materials = _reconnect_materials(imported, slots, output.parent)
        helpers = _hide_helpers(imported)
        asset_collection.asset_mark()
        asset_collection.asset_data.catalog_id = _catalog_id("POLYGON Western/" + category)
        asset_collection.asset_data.description = f"POLYGON Western {category}: {_clean_name(name)}"
        asset_collection.asset_data.tags.new("POLYGON Western")
        asset_collection.asset_data.tags.new(category)
        preview_error = None
        try:
            _render_preview(temporary_scene, asset_collection)
        except Exception as exc:
            preview_error = str(exc)
        # Include the owning clean scene as well as the asset collection.  A
        # collection-only library can be indexed, but opens as an empty scene and
        # may instantiate as empty when dragged from the Asset Browser.
        bpy.data.libraries.write(
            str(output), {temporary_scene, asset_collection},
            path_remap="RELATIVE", fake_user=True, compress=True,
        )
        return {"status": "converted", "source": str(path), "output": str(output), "catalog": category,
                "objects": len(imported), "armatures": [o.name for o in imported if o.type == "ARMATURE"],
                "animations": [o.name for o in imported if o.type == "ARMATURE" and o.animation_data and o.animation_data.action],
                "helpers_hidden": helpers, "materials": materials, "preview_error": preview_error}
    finally:
        bpy.context.window.scene = original_scene
        for obj in imported:
            if obj.name in bpy.data.objects:
                bpy.data.objects.remove(obj, do_unlink=True)
        if temporary_scene.name in bpy.data.scenes:
            bpy.data.scenes.remove(temporary_scene, do_unlink=True)
        if asset_collection and asset_collection.name in bpy.data.collections and asset_collection.users == 0:
            bpy.data.collections.remove(asset_collection)


def run_batch(limit=20, force=False):
    """Convert at most `limit` pending assets. Call repeatedly; existing outputs are skipped."""
    manifest = _load_manifest()
    files = discover()
    categories = {_catalog_for(p.stem, manifest) for p in files}
    _ensure_catalogs(categories)
    LOGS.mkdir(parents=True, exist_ok=True)
    events, processed = [], 0
    for path in files:
        category = _catalog_for(path.stem, manifest)
        output = LIBRARY / category / (path.stem + ".blend")
        if output.exists() and not force:
            events.append({"status": "skipped", "source": str(path), "output": str(output)})
            continue
        if processed >= limit:
            continue
        processed += 1
        try:
            events.append(_write_asset(path, manifest))
        except Exception as exc:
            events.append({"status": "failed", "source": str(path), "error": str(exc), "traceback": traceback.format_exc()})
    log = LOGS / "conversion_events.jsonl"
    with log.open("a", encoding="utf-8") as handle:
        for event in events:
            event["timestamp"] = datetime.now(timezone.utc).isoformat()
            handle.write(json.dumps(event, sort_keys=True) + "\n")
    report = {"discovered": len(files), "processed_this_run": processed,
              "converted_this_run": sum(e["status"] == "converted" for e in events),
              "skipped": sum(e["status"] == "skipped" for e in events),
              "failed_this_run": sum(e["status"] == "failed" for e in events), "events": events}
    (LOGS / "latest_batch_report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    return report
